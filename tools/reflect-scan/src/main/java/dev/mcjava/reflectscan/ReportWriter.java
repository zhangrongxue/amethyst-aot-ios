package dev.mcjava.reflectscan;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.*;

/** Writes the three artifacts produced by a scan. */
public final class ReportWriter {

    private ReportWriter() {
    }

    public static void write(Path out, ReflectionScan.Result r, int jarCount) throws IOException {
        Files.createDirectories(out);
        writeForceLink(out.resolve("force-link-classes.txt"), r);
        writeJson(out.resolve("reflection-report.json"), r, jarCount);
        writeMarkdown(out.resolve("reflection-report.md"), r, jarCount);
    }

    private static void writeForceLink(Path file, ReflectionScan.Result r) throws IOException {
        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by reflect-scan. One RoboVM/MobiVM forceLinkClasses pattern per line.\n");
        sb.append("# Exact classes first, then package wildcards.\n");
        for (String c : r.exactClasses) {
            sb.append(c).append('\n');
        }
        for (String p : r.patterns) {
            if (!r.exactClasses.contains(p)) {
                sb.append(p).append('\n');
            }
        }
        Files.write(file, sb.toString().getBytes(StandardCharsets.UTF_8));
    }

    private static void writeJson(Path file, ReflectionScan.Result r, int jarCount) throws IOException {
        StringBuilder sb = new StringBuilder();
        sb.append("{\n");
        sb.append("  \"tool\": \"reflect-scan\",\n");
        sb.append("  \"jarCount\": ").append(jarCount).append(",\n");
        sb.append("  \"classesScanned\": ").append(r.totalClasses).append(",\n");
        sb.append("  \"hitCount\": ").append(r.hits.size()).append(",\n");
        sb.append("  \"exactClassCount\": ").append(r.exactClasses.size()).append(",\n");
        sb.append("  \"patternCount\": ").append(r.patterns.size()).append(",\n");

        sb.append("  \"perJar\": {\n");
        int i = 0;
        for (Map.Entry<String, Integer> e : r.perJarClasses.entrySet()) {
            sb.append("    ").append(q(e.getKey())).append(": ").append(e.getValue());
            sb.append(++i < r.perJarClasses.size() ? ",\n" : "\n");
        }
        sb.append("  },\n");

        sb.append("  \"services\": [");
        i = 0;
        for (String s : r.services) {
            sb.append(i++ == 0 ? "" : ", ").append(q(s));
        }
        sb.append("],\n");

        sb.append("  \"unresolved\": [");
        i = 0;
        for (String s : r.unresolved) {
            sb.append(i++ == 0 ? "" : ", ").append(q(s));
        }
        sb.append("],\n");

        sb.append("  \"jdkRuntime\": [");
        i = 0;
        for (String s : r.jdkRuntime) {
            sb.append(i++ == 0 ? "" : ", ").append(q(s));
        }
        sb.append("],\n");

        sb.append("  \"forceLinkClasses\": [");
        i = 0;
        for (String p : r.patterns) {
            sb.append(i++ == 0 ? "" : ", ").append(q(p));
        }
        sb.append("],\n");

        sb.append("  \"hits\": [\n");
        i = 0;
        for (Hit h : r.hits) {
            sb.append("    {\"kind\": ").append(q(h.kind))
              .append(", \"owner\": ").append(q(h.owner))
              .append(", \"member\": ").append(q(h.member))
              .append(", \"caller\": ").append(q(h.caller))
              .append(", \"jar\": ").append(q(h.jar))
              .append(", \"evidence\": ").append(q(h.evidence))
              .append("}");
            sb.append(++i < r.hits.size() ? ",\n" : "\n");
        }
        sb.append("  ]\n");
        sb.append("}\n");
        Files.write(file, sb.toString().getBytes(StandardCharsets.UTF_8));
    }

    private static void writeMarkdown(Path file, ReflectionScan.Result r, int jarCount) throws IOException {
        StringBuilder sb = new StringBuilder();
        sb.append("# Reflection scan report\n\n");
        sb.append("| metric | value |\n|---|---:|\n");
        sb.append("| jars scanned | ").append(jarCount).append(" |\n");
        sb.append("| classes scanned | ").append(r.totalClasses).append(" |\n");
        sb.append("| reflection hits | ").append(r.hits.size()).append(" |\n");
        sb.append("| exact classes | ").append(r.exactClasses.size()).append(" |\n");
        sb.append("| forceLink patterns | ").append(r.patterns.size()).append(" |\n");
        sb.append("| service entries | ").append(r.services.size()).append(" |\n");
        sb.append("| unresolved names | ").append(r.unresolved.size()).append(" |\n\n");

        Map<String, Integer> byKind = new TreeMap<>();
        for (Hit h : r.hits) byKind.merge(h.kind, 1, Integer::sum);
        sb.append("## Hits by kind\n\n| kind | count |\n|---|---:|\n");
        for (Map.Entry<String, Integer> e : byKind.entrySet()) {
            sb.append("| ").append(e.getKey()).append(" | ").append(e.getValue()).append(" |\n");
        }

        Map<String, Integer> byJar = new TreeMap<>();
        for (Hit h : r.hits) byJar.merge(h.jar, 1, Integer::sum);
        sb.append("\n## Hits by jar\n\n| jar | hits |\n|---|---:|\n");
        for (Map.Entry<String, Integer> e : byJar.entrySet()) {
            sb.append("| ").append(e.getKey()).append(" | ").append(e.getValue()).append(" |\n");
        }

        sb.append("\n## Top forceLink patterns\n\n```\n");
        int shown = 0;
        for (String p : r.patterns) {
            if (shown++ >= 200) {
                sb.append("... ").append(r.patterns.size() - 200).append(" more\n");
                break;
            }
            sb.append(p).append('\n');
        }
        sb.append("```\n");

        sb.append("\n## Unresolved names (not found in scanned jars)\n\n```\n");
        shown = 0;
        for (String u : r.unresolved) {
            if (shown++ >= 100) {
                sb.append("... ").append(r.unresolved.size() - 100).append(" more\n");
                break;
            }
            sb.append(u).append('\n');
        }
        sb.append("```\n");

        sb.append("\n## JDK runtime names (resolved by RoboVM rt, not force-linked)\n\n```\n");
        for (String u : r.jdkRuntime) {
            sb.append(u).append('\n');
        }
        sb.append("```\n");
        Files.write(file, sb.toString().getBytes(StandardCharsets.UTF_8));
    }

    private static String q(String s) {
        if (s == null) return "null";
        StringBuilder sb = new StringBuilder("\"");
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"': sb.append("\\\""); break;
                case '\\': sb.append("\\\\"); break;
                case '\n': sb.append("\\n"); break;
                case '\r': sb.append("\\r"); break;
                case '\t': sb.append("\\t"); break;
                default:
                    if (c < 0x20) {
                        sb.append(String.format("\\u%04x", (int) c));
                    } else {
                        sb.append(c);
                    }
            }
        }
        return sb.append('"').toString();
    }
}
